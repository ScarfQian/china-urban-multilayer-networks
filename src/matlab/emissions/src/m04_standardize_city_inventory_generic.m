function out = m04_standardize_city_inventory_generic(cfg)
% M04_STANDARDIZE_CITY_INVENTORY_GENERIC
% Convert the raw city inventory workbook into a 313-city standardized table.

required = ["year","workbookPath","cityMrio17Path","codebookCsv","resultsDir"];
for i = 1:numel(required)
    if ~isfield(cfg, required(i))
        error('m04_standardize_city_inventory_generic:MissingCfgField', ...
            'Missing required configuration field: %s', required(i));
    end
end

ensure_dir_local(cfg.resultsDir);
parsed = m02_parse_city_inventory_workbook(cfg.workbookPath);
crosswalkPath = fullfile(cfg.resultsDir, "city_inventory_crosswalk_" + string(cfg.year) + ".csv");
crosswalk = m03_build_inventory_city_crosswalk_313(parsed.cityTable, cfg.codebookCsv, cfg.cityMrio17Path, crosswalkPath);

rawLongPath = fullfile(cfg.resultsDir, "city_inventory_raw_long_" + string(cfg.year) + ".csv");
writetable(parsed.rawLongTable, rawLongPath);

codebook = readtable(cfg.codebookCsv, 'TextType', 'string');
rawRows = cell(0, 19);
for i = 1:height(crosswalk)
    if crosswalk.zero_fill_flag(i) == 1
        rawRows = append_zero_fill_rows_local(rawRows, crosswalk(i, :), codebook, parsed.catalog); %#ok<AGROW>
        continue;
    end

    hit = parsed.rawLongTable.year == crosswalk.year(i) & ...
        parsed.rawLongTable.raw_city_name == crosswalk.raw_city_name(i);
    source = parsed.rawLongTable(hit, :);
    targetInfo = codebook(codebook.city_code == crosswalk.target_city_code(i), :);
    for j = 1:height(source)
        rawRows(end+1, :) = { ... %#ok<AGROW>
            source.year(j), ...
            char(targetInfo.province_name_std(1)), ...
            targetInfo.province_code(1), ...
            char(source.raw_province_name(j)), ...
            char(targetInfo.city_cn(1)), ...
            targetInfo.city_code(1), ...
            char(targetInfo.city_en(1)), ...
            targetInfo.city_id(1), ...
            char(source.raw_city_name(j)), ...
            char(source.raw_city_name_en(j)), ...
            char(source.raw_field_cn(j)), ...
            char(source.field_en(j)), ...
            char(source.field_group(j)), ...
            source.production_direct_flag(j), ...
            source.household_direct_flag(j), ...
            source.indirect_flag(j), ...
            source.total_check_flag(j), ...
            source.value(j) * crosswalk.allocation_share(i), ...
            char(crosswalk.mapping_rule(i))};
    end
end

allocated = cell2table(rawRows, 'VariableNames', { ...
    'year','province_name_std','province_code','raw_province_name','city_name_std','city_code','city_name_en','city_id', ...
    'raw_city_name','raw_city_name_en','raw_field_cn','field_en','field_group', ...
    'production_direct_flag','household_direct_flag','indirect_flag','total_check_flag','value','mapping_rule'});

standardized = collapse_standardized_rows_local(allocated);
legacyPath = fullfile(cfg.resultsDir, "city_inventory_standardized_" + string(cfg.year) + ".csv");
canonicalLongPath = fullfile(cfg.resultsDir, "city_inventory_standardized_long_" + string(cfg.year) + ".csv");
writetable(standardized, legacyPath);
writetable(standardized, canonicalLongPath);

out = struct();
out.year = cfg.year;
out.rawLongTable = parsed.rawLongTable;
out.standardizedTable = standardized;
out.crosswalkTable = crosswalk;
out.rawLongPath = string(rawLongPath);
out.standardizedPath = string(canonicalLongPath);
out.standardizedLongPath = string(canonicalLongPath);
out.standardizedLegacyPath = string(legacyPath);
out.crosswalkPath = string(crosswalkPath);
end

function rows = append_zero_fill_rows_local(rows, crosswalkRow, codebook, catalog)
targetInfo = codebook(codebook.city_code == crosswalkRow.target_city_code, :);
for i = 1:height(catalog)
    rows(end+1, :) = { ... %#ok<AGROW>
        crosswalkRow.year, ...
        char(targetInfo.province_name_std(1)), ...
        targetInfo.province_code(1), ...
        "", ...
        char(targetInfo.city_cn(1)), ...
        targetInfo.city_code(1), ...
        char(targetInfo.city_en(1)), ...
        targetInfo.city_id(1), ...
        "", ...
        "", ...
        char(catalog.raw_field_cn(i)), ...
        char(catalog.field_en(i)), ...
        char(catalog.field_group(i)), ...
        double(catalog.production_direct_flag(i)), ...
        double(catalog.household_direct_flag(i)), ...
        double(catalog.indirect_flag(i)), ...
        double(catalog.total_check_flag(i)), ...
        0, ...
        char(crosswalkRow.mapping_rule)};
end
end

function standardized = collapse_standardized_rows_local(allocated)
keyTable = allocated(:, {'year','province_name_std','province_code','city_name_std','city_code','city_name_en','city_id', ...
    'raw_field_cn','field_en','field_group','production_direct_flag','household_direct_flag','indirect_flag','total_check_flag'});
[G, keys] = findgroups(keyTable);
value = splitapply(@sum, allocated.value, G);
sourceCityCount = splitapply(@(x) numel(unique(string(x(string(x) ~= "")))), allocated.raw_city_name, G);
mappingRule = splitapply(@collapse_rule_local, allocated.mapping_rule, G);
standardized = keys;
standardized.value = value;
standardized.source_city_count = sourceCityCount;
standardized.mapping_rule = mappingRule;
standardized.use_in_production_q = double(standardized.production_direct_flag == 1);
standardized = sortrows(standardized, {'province_code','city_code','field_en'});
end

function out = collapse_rule_local(values)
u = unique(string(values));
u = u(strlength(u) > 0);
if isempty(u)
    out = "";
elseif numel(u) == 1
    out = u(1);
else
    out = strjoin(cellstr(u), '|');
end
end

function ensure_dir_local(dirPath)
if ~exist(dirPath, 'dir')
    mkdir(dirPath);
end
end
