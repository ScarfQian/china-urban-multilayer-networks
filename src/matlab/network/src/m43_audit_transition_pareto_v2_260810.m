function audit = m43_audit_transition_pareto_v2_260810( ...
        inputs, v1, continuousBound, scopeFrontier, scopeSelections, ...
        gapDecomposition, attainment, attainmentSummary, similarity, ...
        substitutions, randomIntervalSummary, manifest, cfg)
% M43_AUDIT_TRANSITION_PARETO_V2_260810
% 审计 Pareto v2 的科学边界、数值关系、集合闭合和输出隔离

checks = cell(0, 6);
expectedGroupsPerYear = 8 + cfg.randomRepeats + 1;
expectedScopeRows = numel(cfg.years) * numel(cfg.scopeEta) * ...
    expectedGroupsPerYear;

expectedOutput = canonical_path_local(study_path('generated', 'network', ...
    'revised_transition_pareto_extension_v2'));
actualOutput = canonical_path_local(cfg.outputDir);
add_check("v2_output_directory", actualOutput == expectedOutput, NaN, ...
    expectedOutput, actualOutput, "independent v2 result directory");
add_check("output_outside_final_freeze", ...
    ~inside_path_local(actualOutput, canonical_path_local(cfg.finalFreezeDir)), ...
    NaN, "true", "true", "final_freeze remains read-only");
add_check("output_outside_v1_results", ...
    ~inside_path_local(actualOutput, canonical_path_local(cfg.v1ResultDir)), ...
    NaN, "true", "true", "v1 results remain read-only");

for year = cfg.years
    key = sprintf('y%d', year);
    gov = inputs.governance.(key);
    add_check("unique_city_count", ...
        height(gov) == cfg.nCities && ...
        numel(unique(gov.city_code)) == cfg.nCities, year, ...
        string(cfg.nCities), string(height(gov)), "pure-city governance input");
    proxyCount = sum(ismember(gov.city_code, cfg.excludedProxyCodes));
    add_check("proxy_city_count", proxyCount == 0, year, ...
        "0", string(proxyCount), "frozen governance input");
    zeroCarbon = gov(abs(gov.CB_share) <= cfg.objectiveTolerance, :);
    shiheziOk = height(zeroCarbon) == 1 && ...
        zeroCarbon.city_code(1) == 659001;
    add_check("zero_carbon_endpoint_city", shiheziOk, year, ...
        "659001 Shihezi only", join(string(zeroCarbon.city_code), ';'), ...
        "zero-carbon city may be excluded at ER=0.90");

    exact = sortrows(v1.frontier(v1.frontier.year == year, :), ...
        'economic_loss_budget');
    monotonicOk = all(diff(exact.carbon_reduction) >= ...
        -cfg.feasibilityTolerance);
    add_check("v1_frontier_monotonic_carbon_reduction", monotonicOk, ...
        year, "nondecreasing with budget", string(monotonicOk), ...
        "v1 system frontier reused without recomputation");
    endpoint1 = exact(abs(exact.eta - 1) <= cfg.objectiveTolerance, :);
    endpoint90 = exact(abs(exact.eta - 0.90) <= cfg.objectiveTolerance, :);
    endpointOk = height(endpoint1) == 1 && height(endpoint90) == 1 && ...
        abs(endpoint1.carbon_reduction) <= cfg.objectiveTolerance && ...
        abs(endpoint1.economic_loss) <= cfg.objectiveTolerance && ...
        abs(endpoint90.carbon_reduction - cfg.mainTau) <= ...
        cfg.feasibilityTolerance && ...
        endpoint90.economic_loss <= 0.10 + cfg.feasibilityTolerance;
    add_check("v1_frontier_endpoints", endpointOk, year, ...
        "ER=1: CR=EL=0; ER=0.90: CR=0.10 and EL<=0.10", ...
        string(endpointOk), "do not require 309 selected cities");
    selected90 = v1.frontierSelections( ...
        v1.frontierSelections.year == year & ...
        abs(v1.frontierSelections.eta - 0.90) <= cfg.objectiveTolerance, :);
    positiveCarbonCodes = gov.city_code(gov.CB_share > cfg.objectiveTolerance);
    positiveCovered = all(ismember(positiveCarbonCodes, selected90.city_code));
    add_check("positive_carbon_cities_covered_at_ER090", ...
        positiveCovered, year, "all", string(positiveCovered), ...
        "zero-carbon Shihezi need not be selected");
end

v1Pass = isfield(v1.manifest, 'audit_status') && ...
    strcmpi(string(v1.manifest.audit_status), "PASS");
add_check("v1_manifest_audit_status", v1Pass, NaN, ...
    "PASS", string(v1.manifest.audit_status), ...
    "202-point system frontier is inherited");
add_check("v1_frontier_row_count", height(v1.frontier) == ...
    numel(cfg.years) * numel(cfg.erGrid), NaN, ...
    string(numel(cfg.years) * numel(cfg.erGrid)), ...
    string(height(v1.frontier)), "not recomputed in v2");

add_check("continuous_bound_row_count", height(continuousBound) == ...
    numel(cfg.years) * numel(cfg.erGrid), NaN, ...
    string(numel(cfg.years) * numel(cfg.erGrid)), ...
    string(height(continuousBound)), "one row per year and ER point");
minUpperGap = min(continuousBound.continuous_carbon_reduction - ...
    continuousBound.binary_frontier_carbon_reduction);
add_check("continuous_bound_not_below_binary", ...
    minUpperGap >= -cfg.feasibilityTolerance, NaN, ...
    sprintf('>=-%.1e', cfg.feasibilityTolerance), ...
    sprintf('%.12g', minUpperGap), "LP relaxation upper bound");
maxContinuousBudgetViolation = max(continuousBound.continuous_economic_loss - ...
    continuousBound.economic_loss_budget);
add_check("continuous_bound_budget_feasibility", ...
    maxContinuousBudgetViolation <= cfg.feasibilityTolerance, NaN, ...
    sprintf('<=%.1e', cfg.feasibilityTolerance), ...
    sprintf('%.12g', maxContinuousBudgetViolation), "production-flow-loss budget");
add_check("continuous_bound_fractional_city_count", ...
    all(continuousBound.n_fractional_cities <= 1), NaN, ...
    "<=1 per row", string(max(continuousBound.n_fractional_cities)), ...
    "fractional knapsack structure");

add_check("scope_frontier_row_count", height(scopeFrontier) == ...
    expectedScopeRows, NaN, string(expectedScopeRows), ...
    string(height(scopeFrontier)), ...
    "8 governance + 50 random + 1 technical benchmark");
statusOk = all(string(scopeFrontier.stage1_status) == "OPTIMAL") && ...
    all(string(scopeFrontier.stage2_status) == "OPTIMAL") && ...
    all(string(scopeFrontier.stage3_status) == "OPTIMAL");
add_check("scope_lexicographic_status", statusOk, NaN, ...
    "all OPTIMAL", string(statusOk), ...
    "optimal within configured numerical tolerances");
maxRelativeGap = max([scopeFrontier.stage1_relative_gap; ...
    scopeFrontier.stage2_relative_gap; scopeFrontier.stage3_relative_gap]);
maxAbsoluteBoundGap = max([scopeFrontier.stage1_absolute_bound_gap; ...
    scopeFrontier.stage2_absolute_bound_gap; ...
    scopeFrontier.stage3_absolute_bound_gap]);
add_check("scope_solver_relative_gap", ...
    maxRelativeGap <= cfg.solverGapAcceptance, NaN, ...
    sprintf('<=%.1e', cfg.solverGapAcceptance), ...
    sprintf('%.12g', maxRelativeGap), "all lexicographic stages");
add_check("scope_solver_absolute_bound_gap", ...
    maxAbsoluteBoundGap <= cfg.solverAbsoluteGapAcceptance, NaN, ...
    sprintf('<=%.1e', cfg.solverAbsoluteGapAcceptance), ...
    sprintf('%.12g', maxAbsoluteBoundGap), "all lexicographic stages");
maxScopeBudgetViolation = max(scopeFrontier.scope_capped_economic_loss - ...
    scopeFrontier.economic_loss_budget);
maxCityCapViolation = max(scopeFrontier.scope_capped_selected_cities - ...
    scopeFrontier.candidate_K);
add_check("scope_budget_feasibility", ...
    maxScopeBudgetViolation <= cfg.feasibilityTolerance, NaN, ...
    sprintf('<=%.1e', cfg.feasibilityTolerance), ...
    sprintf('%.12g', maxScopeBudgetViolation), "EL<=1-eta");
add_check("scope_city_cap", maxCityCapViolation <= 0, NaN, ...
    "<=0", string(maxCityCapViolation), "sum(x)<=candidate_K");

maxCandidateOverScope = max(gapDecomposition.candidate_carbon_reduction - ...
    gapDecomposition.scope_capped_optimal_reduction);
maxScopeOverSystem = max(gapDecomposition.scope_capped_optimal_reduction - ...
    gapDecomposition.unrestricted_optimal_reduction);
add_check("candidate_not_above_scope_optimum", ...
    maxCandidateOverScope <= cfg.feasibilityTolerance, NaN, ...
    sprintf('<=%.1e', cfg.feasibilityTolerance), ...
    sprintf('%.12g', maxCandidateOverScope), "candidate is feasible under its cap");
add_check("scope_optimum_not_above_system_frontier", ...
    maxScopeOverSystem <= cfg.feasibilityTolerance, NaN, ...
    sprintf('<=%.1e', cfg.feasibilityTolerance), ...
    sprintf('%.12g', maxScopeOverSystem), "scope problem is more constrained");

[selectionOk, maxSelectionELDiff, maxSelectionCRDiff] = ...
    audit_scope_selections_local(scopeFrontier, scopeSelections, cfg);
add_check("scope_selection_reconstruction", selectionOk, NaN, ...
    "true", string(selectionOk), sprintf('max_EL_diff=%.12g; max_CR_diff=%.12g', ...
    maxSelectionELDiff, maxSelectionCRDiff));

maxResidual = max(abs(gapDecomposition.decomposition_residual));
add_check("gap_decomposition_closure", ...
    maxResidual <= cfg.objectiveTolerance + cfg.feasibilityTolerance, NaN, ...
    sprintf('<=%.1e', cfg.objectiveTolerance + cfg.feasibilityTolerance), ...
    sprintf('%.12g', maxResidual), "system gap = coverage + ranking");
finiteShares = [gapDecomposition.coverage_component_share; ...
    gapDecomposition.ranking_component_share];
finiteShares = finiteShares(isfinite(finiteShares));
add_check("gap_component_share_bounds", ...
    all(finiteShares >= -cfg.feasibilityTolerance & ...
    finiteShares <= 1 + cfg.feasibilityTolerance), NaN, ...
    "[0,1]", sprintf('[%.6g, %.6g]', min(finiteShares), max(finiteShares)), ...
    "finite decomposition shares only");

ifar = attainment.integrated_frontier_attainment;
add_check("integrated_frontier_attainment_bounds", ...
    all(ifar >= -cfg.feasibilityTolerance & ...
    ifar <= 1 + cfg.feasibilityTolerance), NaN, ...
    "[0,1]", sprintf('[%.6g, %.6g]', min(ifar), max(ifar)), ...
    "fixed 101-point grid without smoothing");
randomIFAR = attainmentSummary(string(attainmentSummary.strategy) == ...
    "random", :);
add_check("random_IFAR_repeat_count", ...
    height(randomIFAR) == numel(cfg.years) && ...
    all(randomIFAR.n_repeats == cfg.randomRepeats), NaN, ...
    sprintf('%d years and %d repeats', numel(cfg.years), cfg.randomRepeats), ...
    sprintf('%d rows', height(randomIFAR)), "repeat-wise IFAR before summary");

jaccardValues = [similarity.jaccard_candidate_vs_scope_exact; ...
    similarity.jaccard_candidate_vs_unrestricted_exact];
add_check("jaccard_bounds", ...
    all(jaccardValues >= -cfg.feasibilityTolerance & ...
    jaccardValues <= 1 + cfg.feasibilityTolerance), NaN, ...
    "[0,1]", sprintf('[%.6g, %.6g]', min(jaccardValues), ...
    max(jaccardValues)), "deterministic and technical groups");
setClosure = all(similarity.n_common + similarity.n_candidate_only == ...
    similarity.candidate_count) && ...
    all(similarity.n_common + similarity.n_scope_exact_only == ...
    similarity.scope_exact_count);
add_check("city_set_count_closure", setClosure, NaN, ...
    "true", string(setClosure), "candidate and scope-exact unions");
[substitutionOk, maxSubELDiff, maxSubCRDiff] = ...
    audit_substitutions_local(similarity, substitutions, cfg);
add_check("city_substitution_contribution_closure", substitutionOk, NaN, ...
    "true", string(substitutionOk), sprintf('max_EL_diff=%.12g; max_CR_diff=%.12g', ...
    maxSubELDiff, maxSubCRDiff));

randomRowsExpected = numel(cfg.years) * numel(cfg.scopeEta);
randomBoundsOk = all(randomIntervalSummary.n_repeats == cfg.randomRepeats) && ...
    all(randomIntervalSummary.candidate_carbon_reduction_p025 <= ...
    randomIntervalSummary.candidate_carbon_reduction_p975) && ...
    all(randomIntervalSummary.relative_system_gap_p025 <= ...
    randomIntervalSummary.relative_system_gap_p975);
add_check("random_interval_summary", ...
    height(randomIntervalSummary) == randomRowsExpected && randomBoundsOk, NaN, ...
    sprintf('%d rows, 50 repeats, p025<=p975', randomRowsExpected), ...
    sprintf('%d rows', height(randomIntervalSummary)), ...
    "95 percent empirical interval");

createdFiles = string(manifest.files_created);
missingFiles = strings(0, 1);
for i = 1:numel(createdFiles)
    if contains(createdFiles(i), "audit_checks") || ...
            contains(createdFiles(i), "audit_report")
        continue;
    end
    if ~exist(fullfile(char(cfg.outputDir), char(createdFiles(i))), 'file')
        missingFiles(end + 1, 1) = createdFiles(i); %#ok<AGROW>
    end
end
add_check("required_non_audit_outputs_exist", isempty(missingFiles), NaN, ...
    "all", strjoin(missingFiles, ';'), "date-prefixed v2 outputs");

checkTable = cell2table(checks, 'VariableNames', ...
    {'check', 'status', 'year', 'expected', 'actual', 'detail'});
overallStatus = "PASS";
if any(checkTable.status ~= "PASS")
    overallStatus = "FAIL";
end

prefix = char(cfg.fileDatePrefix);
checksPath = fullfile(char(cfg.outputDir), ...
    [prefix 'transition_pareto_v2_audit_checks.csv']);
reportPath = fullfile(char(cfg.outputDir), ...
    [prefix 'transition_pareto_v2_audit_report.md']);
writetable(checkTable, checksPath);
write_report_local(reportPath, checkTable, overallStatus, cfg);

manifest.audit_status = char(overallStatus);
manifest.audit_report = reportPath;
manifest.audit_checks = checksPath;
manifest.maximum_scope_relative_gap = maxRelativeGap;
manifest.maximum_scope_absolute_bound_gap = maxAbsoluteBoundGap;
write_manifest_local(manifest);
append_summary_status_local(manifest.summaryPath, overallStatus);

audit = struct();
audit.status = overallStatus;
audit.checks = checkTable;
audit.reportPath = string(reportPath);
audit.checksPath = string(checksPath);
audit.manifest = manifest;

    function add_check(name, condition, year, expected, actual, detail)
        status = "FAIL";
        if condition
            status = "PASS";
        end
        checks(end + 1, :) = {string(name), status, year, ...
            string(expected), string(actual), string(detail)};
    end
end

function [allOk, maxELDiff, maxCRDiff] = ...
        audit_scope_selections_local(frontier, selections, cfg)
allOk = true;
maxELDiff = 0;
maxCRDiff = 0;
for i = 1:height(frontier)
    row = frontier(i, :);
    sub = selections(selections.year == row.year & ...
        abs(selections.eta - row.eta) <= cfg.objectiveTolerance & ...
        string(selections.strategy) == string(row.strategy) & ...
        selections.repeat_id == row.repeat_id, :);
    actualEL = sum(sub.economic_loss_contribution);
    actualCR = sum(sub.carbon_reduction_contribution);
    maxELDiff = max(maxELDiff, abs(actualEL - row.scope_capped_economic_loss));
    maxCRDiff = max(maxCRDiff, abs(actualCR - row.scope_capped_carbon_reduction));
    allOk = allOk && height(sub) == row.scope_capped_selected_cities && ...
        abs(actualEL - row.scope_capped_economic_loss) <= ...
        cfg.feasibilityTolerance && ...
        abs(actualCR - row.scope_capped_carbon_reduction) <= ...
        cfg.feasibilityTolerance;
end
end

function [allOk, maxELDiff, maxCRDiff] = ...
        audit_substitutions_local(similarity, substitutions, cfg)
allOk = true;
maxELDiff = 0;
maxCRDiff = 0;
for i = 1:height(similarity)
    row = similarity(i, :);
    sub = substitutions(substitutions.year == row.year & ...
        abs(substitutions.eta - row.eta) <= cfg.objectiveTolerance & ...
        string(substitutions.strategy) == string(row.strategy), :);
    removed = sub(string(sub.membership_status) == "candidate_only", :);
    added = sub(string(sub.membership_status) == "scope_exact_only", :);
    netEL = sum(added.economic_loss_contribution) - ...
        sum(removed.economic_loss_contribution);
    netCR = sum(added.carbon_reduction_contribution) - ...
        sum(removed.carbon_reduction_contribution);
    maxELDiff = max(maxELDiff, abs(netEL - row.net_economic_loss_change));
    maxCRDiff = max(maxCRDiff, abs(netCR - row.net_carbon_reduction_change));
    allOk = allOk && ...
        abs(netEL - row.net_economic_loss_change) <= cfg.feasibilityTolerance && ...
        abs(netCR - row.net_carbon_reduction_change) <= cfg.feasibilityTolerance;
end
end

function inside = inside_path_local(path, root)
inside = path == root || startsWith(path, root + filesep);
end

function path = canonical_path_local(pathValue)
fileObject = java.io.File(char(pathValue));
path = string(char(fileObject.getCanonicalPath()));
end

function write_report_local(path, checks, status, cfg)
fid = fopen(path, 'w');
if fid < 0
    error('m43_pareto_v2:ReportOpenFailed', ...
        'Cannot write audit report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# 转型策略精确前沿第二轮完成模块审计报告\n\n');
fprintf(fid, '- 日期：2026-08-10\n');
fprintf(fid, '- 执行者：%s\n', char(cfg.executor));
fprintf(fid, '- 冻结输入：`%s`\n', char(cfg.sourceTransitionDir));
fprintf(fid, '- v1 结果：`%s`\n', char(cfg.v1ResultDir));
fprintf(fid, '- v2 输出：`%s`\n', char(cfg.outputDir));
fprintf(fid, '- 最优性表述：在设定数值容限内最优\n\n');
fprintf(fid, '| Check | Status | Year | Expected | Actual | Detail |\n');
fprintf(fid, '|---|---|---:|---|---|---|\n');
for i = 1:height(checks)
    yearText = '';
    if isfinite(checks.year(i))
        yearText = sprintf('%d', checks.year(i));
    end
    fprintf(fid, '| %s | %s | %s | %s | %s | %s |\n', ...
        clean_md_local(checks.check(i)), clean_md_local(checks.status(i)), ...
        yearText, clean_md_local(checks.expected(i)), ...
        clean_md_local(checks.actual(i)), clean_md_local(checks.detail(i)));
end
fprintf(fid, '\nTRANSITION_PARETO_V2_AUDIT_STATUS = %s\n', status);
end

function text = clean_md_local(value)
text = char(replace(string(value), '|', '/'));
end

function write_manifest_local(manifest)
path = char(manifest.path);
json = jsonencode(manifest, 'PrettyPrint', true);
fid = fopen(path, 'w');
if fid < 0
    error('m43_pareto_v2:ManifestOpenFailed', ...
        'Cannot update manifest: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fwrite(fid, json, 'char');
fwrite(fid, newline, 'char');
end

function append_summary_status_local(path, status)
fid = fopen(char(path), 'a');
if fid < 0
    error('m43_pareto_v2:SummaryOpenFailed', ...
        'Cannot update run summary: %s', char(path));
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '\n\n=========\n\n## 最终审计\n\n');
fprintf(fid, '`TRANSITION_PARETO_V2_AUDIT_STATUS = %s`\n', status);
end
