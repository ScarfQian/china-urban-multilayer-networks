function out = m07_validate_layer_construction(layerBundle, alignment, inputs, yearValue, cfg)
% M07_VALIDATE_LAYER_CONSTRUCTION
% Check city-list equality, proxy cleanliness, Shihezi zero-fill status,
%   non-negativity, zero-output handling, and matrix dimensional integrity
%   before network metrics are computed.

yearField = "y" + string(yearValue);
carbonTable = inputs.carbonByYear.(yearField);
cityCoverage = inputs.cityCoverageReport;
cityReport = alignment.cityReport;
sampleRows = cityReport.included_in_sample == 1;

metrics = cell(0, 4);
metrics(end + 1, :) = metric_row_local(yearValue, "city_alignment_mrio_carbon", ...
    double(all(cityReport.in_carbon_2015(sampleRows) == 1)) * double(yearValue == 2015) + ...
    double(all(cityReport.in_carbon_2020(sampleRows) == 1)) * double(yearValue == 2020), ...
    "All canonical cities must appear in the final carbon package."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "city_alignment_mrio_investment", ...
    double(all((yearValue == 2015 & cityReport.in_investment_2015(sampleRows) == 1) | (yearValue == 2020 & cityReport.in_investment_2020(sampleRows) == 1))), ...
    "All canonical cities must appear after investment-city alignment."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "sample_node_count", alignment.numCities, ...
    "Number of cities retained under the active sample_mode."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "excluded_proxy_unit_count", sum(cityReport.included_in_sample == 0), ...
    "Proxy province units excluded only when sample_mode is pure_city."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "hidden_proxy_row_count", ...
    sum(contains(lower(string(carbonTable.source_basis)), "proxy")), ...
    "Final carbon package should not expose proxy-based rows."); %#ok<AGROW>

shiheziRows = carbonTable.city_name_std == "石河子";
metrics(end + 1, :) = metric_row_local(yearValue, "shihezi_zero_fill_rows", sum(shiheziRows), ...
    "Shihezi should remain explicitly present in the final carbon package."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "shihezi_zero_fill_sum", sum(double(carbonTable.co2_total(shiheziRows))), ...
    "Shihezi direct emissions should follow the explicit zero-fill rule."); %#ok<AGROW>

if ~isempty(cityCoverage)
    coverageCol = "zero_fill_" + string(yearValue);
    zeroFillCount = sum(double(cityCoverage.(coverageCol)) == 1);
else
    zeroFillCount = NaN;
end
metrics(end + 1, :) = metric_row_local(yearValue, "coverage_zero_fill_city_count", zeroFillCount, ...
    "Expected explicit zero-fill count from the carbon-matching coverage report."); %#ok<AGROW>

metrics(end + 1, :) = metric_row_local(yearValue, "investment_negative_edge_count", nnz(layerBundle.investment.W < -cfg.zeroTolerance), ...
    "Investment layer must be non-negative."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "economic_negative_edge_count", nnz(layerBundle.economic.W < -cfg.zeroTolerance), ...
    "Economic layer must be non-negative."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "carbon_negative_edge_count", nnz(layerBundle.carbon.W < -cfg.zeroTolerance), ...
    "Carbon layer must be non-negative."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "zero_output_sector_count", layerBundle.carbonIntensity.zeroOutputCount, ...
    "City-sector cells with zero output."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "zero_output_zero_fill_count", layerBundle.carbonIntensity.zeroOutputZeroFillCount, ...
    "Zero-output city-sector cells handled with zero carbon intensity."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "positive_emission_zero_output_count", layerBundle.carbonIntensity.positiveEmissionZeroOutputCount, ...
    "Positive direct emissions attached to zero-output MRIO4 cells; q is explicitly set to zero and flagged."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "positive_emission_zero_output_emission", layerBundle.carbonIntensity.positiveEmissionZeroOutputEmission, ...
    "Emission mass attached to zero-output MRIO4 cells."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "investment_dim_ok", ...
    double(isequal(size(layerBundle.investment.W), [alignment.numCities, alignment.numCities])), ...
    "Investment layer must be N x N."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "economic_dim_ok", ...
    double(isequal(size(layerBundle.economic.W), [alignment.numCities, alignment.numCities])), ...
    "Economic layer must be N x N."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "carbon_dim_ok", ...
    double(isequal(size(layerBundle.carbon.W), [alignment.numCities, alignment.numCities])), ...
    "Carbon layer must be N x N."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "distance_matrix_missing_offdiag", ...
    sum(isnan(alignment.distanceMatrixKm(~eye(alignment.numCities)))), ...
    "Off-diagonal distance entries should be available for QAP."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "same_province_dim_ok", ...
    double(isequal(size(alignment.sameProvinceMatrix), [alignment.numCities, alignment.numCities])), ...
    "Same-province dummy matrix must be N x N."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "investment_collapsed_intracity_weight", ...
    layerBundle.investment.collapsedDiagonalWeight, ...
    "Raw investment edges that collapse to intracity links after 368->313 alignment."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "investment_excluded_by_sample_edge_count", ...
    layerBundle.investment.excludedBySampleEdgeCount, ...
    "Raw investment edges removed because they map only to proxy sample units excluded in pure_city mode."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "investment_excluded_by_sample_weight", ...
    layerBundle.investment.excludedBySampleWeight, ...
    "Investment frequency removed because the mapped source or target is outside the active sample."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "investment_total_weight", ...
    layerBundle.investment.totalWeight, ...
    "Total aligned investment frequency after excluding intracity links."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "economic_total_weight", ...
    layerBundle.economic.totalWeight, ...
    "Total intercity economic flow after removing intracity links."); %#ok<AGROW>
metrics(end + 1, :) = metric_row_local(yearValue, "carbon_total_weight", ...
    layerBundle.carbon.totalWeight, ...
    "Total intercity carbon flow after removing intracity links."); %#ok<AGROW>

validationTable = cell2table(metrics, 'VariableNames', {'year','metric','value','note'});
outputCsv = fullfile(cfg.resultsDir, "layer_construction_validation_" + string(yearValue) + ".csv");
writetable(validationTable, outputCsv);

out = struct();
out.year = yearValue;
out.validationTable = validationTable;
out.outputCsv = string(outputCsv);
end

function row = metric_row_local(yearValue, metricName, value, note)
row = {yearValue, char(metricName), double(value), char(note)};
end
