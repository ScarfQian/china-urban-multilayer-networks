function audit = m37_audit_transition_pareto_extension_260810( ...
        inputs, prefixes, ratioOrders, consistency, frontier, selections, ...
        gaps, randomSummary, keyEtaSummary, manifest, cfg)
% M37_AUDIT_TRANSITION_PARETO_EXTENSION_260810
% 审计精确前沿扩展的样本、前缀、求解状态、效率缺口和输出完整性

checks = cell(0, 6);
expectedGroupsPerYear = 8 + cfg.randomRepeats + 1;
expectedPrefixRowsPerYear = expectedGroupsPerYear * (cfg.nCities + 1);

outputOutsideFreeze = ~startsWith(string(cfg.outputDir), ...
    string(cfg.finalFreezeDir) + filesep);
add_check("output_directory_outside_final_freeze", outputOutsideFreeze, NaN, ...
    "true", string(outputOutsideFreeze), char(cfg.outputDir));

for year = cfg.years
    key = sprintf('y%d', year);
    gov = inputs.governance.(key);
    current = prefixes.(key);

    add_check("unique_city_count", numel(unique(gov.city_code)) == cfg.nCities, ...
        year, string(cfg.nCities), string(numel(unique(gov.city_code))), ...
        "frozen governance input");
    proxyCount = sum(ismember(gov.city_code, cfg.excludedProxyCodes));
    add_check("proxy_city_count", proxyCount == 0, year, "0", ...
        string(proxyCount), "frozen governance input");
    add_check("PC_share_sum", abs(sum(gov.PC_share) - 1) <= ...
        cfg.feasibilityTolerance, year, "1", sprintf('%.17g', sum(gov.PC_share)), ...
        "economic-flow shares");
    add_check("CB_share_sum", abs(sum(gov.CB_share) - 1) <= ...
        cfg.feasibilityTolerance, year, "1", sprintf('%.17g', sum(gov.CB_share)), ...
        "carbon-flow shares");

    groupKeys = unique(current(:, {'year', 'strategy', 'repeat_id'}), ...
        'rows', 'stable');
    add_check("prefix_group_count", height(groupKeys) == expectedGroupsPerYear, ...
        year, string(expectedGroupsPerYear), string(height(groupKeys)), ...
        "8 deterministic + 50 random + 1 technical benchmark");
    add_check("prefix_row_count", height(current) == expectedPrefixRowsPerYear, ...
        year, string(expectedPrefixRowsPerYear), string(height(current)), ...
        "310 rows per prefix group");

    [prefixGroupOk, maxPhiDiff, maxERDiff, maxELDiff, maxCRDiff] = ...
        audit_prefix_groups_local(current, cfg);
    add_check("prefix_K_0_to_309_and_310_points", prefixGroupOk, year, ...
        "true", string(prefixGroupOk), "all strategy-repeat groups");
    add_check("prefix_phi_formula", maxPhiDiff <= cfg.objectiveTolerance, year, ...
        sprintf('<=%.1e', cfg.objectiveTolerance), sprintf('%.12g', maxPhiDiff), ...
        "phi=K/309");
    add_check("prefix_ER_formula", maxERDiff <= cfg.objectiveTolerance, year, ...
        sprintf('<=%.1e', cfg.objectiveTolerance), sprintf('%.12g', maxERDiff), ...
        "ER=1-EL");
    add_check("prefix_EL_cumulative_formula", maxELDiff <= cfg.objectiveTolerance, year, ...
        sprintf('<=%.1e', cfg.objectiveTolerance), sprintf('%.12g', maxELDiff), ...
        "EL=tau*cumulative PC_share");
    add_check("prefix_CR_cumulative_formula", maxCRDiff <= cfg.objectiveTolerance, year, ...
        sprintf('<=%.1e', cfg.objectiveTolerance), sprintf('%.12g', maxCRDiff), ...
        "CR=tau*cumulative CB_share");

    randomRepeats = unique(current.repeat_id(current.strategy == "random"));
    add_check("random_repeat_count", numel(randomRepeats) == cfg.randomRepeats, ...
        year, string(cfg.randomRepeats), string(numel(randomRepeats)), ...
        "each repeat has its own 310-point prefix");

    ratio = ratioOrders(ratioOrders.year == year, :);
    ratioSorted = height(ratio) == cfg.nCities && ...
        all(diff(ratio.ranking_score) <= cfg.objectiveTolerance);
    add_check("carbon_economic_ratio_order", ratioSorted, year, ...
        "309 rows, nonincreasing ratio", ...
        sprintf('%d rows; max positive diff=%.12g', height(ratio), ...
        max([0; diff(ratio.ranking_score)])), ...
        "technical benchmark only");

    exact = frontier(frontier.year == year, :);
    add_check("frontier_grid_point_count", height(exact) == numel(cfg.erGrid), ...
        year, string(numel(cfg.erGrid)), string(height(exact)), ...
        "ER=1.000:-0.001:0.900");
    etaOk = height(exact) == numel(cfg.erGrid) && ...
        max(abs(sort(exact.eta, 'descend') - cfg.erGrid')) <= ...
        cfg.objectiveTolerance;
    add_check("frontier_eta_grid", etaOk, year, "exact configured grid", ...
        string(etaOk), "101 budget points");
end

consistencyOk = all(consistency.status == "PASS");
maxConsistencyDiff = max(abs([consistency.carbon_reduction_difference; ...
    consistency.economic_retention_difference; ...
    consistency.economic_loss_difference]));
add_check("old_one_percent_grid_consistency", consistencyOk && ...
    maxConsistencyDiff <= cfg.consistencyTolerance, NaN, ...
    sprintf('all PASS and <=%.1e', cfg.consistencyTolerance), ...
    sprintf('rows=%d; max_diff=%.12g', height(consistency), maxConsistencyDiff), ...
    "old curves used only for consistency verification");

statusOk = all(frontier.stage1_status == "OPTIMAL") && ...
    all(frontier.stage2_status == "OPTIMAL") && ...
    all(frontier.stage3_status == "OPTIMAL");
add_check("all_lexicographic_stages_global_optimal", statusOk, NaN, ...
    "all OPTIMAL", string(statusOk), "three stages at every frontier point");

maxGap = max([frontier.stage1_relative_gap; frontier.stage2_relative_gap; ...
    frontier.stage3_relative_gap]);
add_check("solver_relative_gap", isfinite(maxGap) && ...
    maxGap <= cfg.mipGapTolerance + eps(cfg.mipGapTolerance), NaN, ...
    sprintf('<=%.1e', cfg.mipGapTolerance), sprintf('%.12g', maxGap), ...
    "maximum over all years, budgets and lexicographic stages");

maxBudgetViolation = max(frontier.economic_loss - ...
    frontier.economic_loss_budget);
add_check("frontier_budget_feasibility", maxBudgetViolation <= ...
    cfg.feasibilityTolerance, NaN, sprintf('<=%.1e', cfg.feasibilityTolerance), ...
    sprintf('%.12g', maxBudgetViolation), "EL<=1-eta");

[selectionOk, maxSelectionELDiff, maxSelectionCRDiff, selectionProxyCount] = ...
    audit_selections_local(frontier, selections, cfg);
add_check("frontier_selection_reconstruction", selectionOk, NaN, "true", ...
    string(selectionOk), sprintf('max_EL_diff=%.12g; max_CR_diff=%.12g', ...
    maxSelectionELDiff, maxSelectionCRDiff));
add_check("frontier_selection_proxy_count", selectionProxyCount == 0, NaN, ...
    "0", string(selectionProxyCount), "all exact-frontier selections");

minDominanceGap = min(gaps.carbon_reduction_efficiency_gap);
add_check("exact_frontier_dominates_strategy_prefixes", ...
    minDominanceGap >= -cfg.feasibilityTolerance && ...
    all(gaps.frontier_dominance_status == "PASS"), NaN, ...
    sprintf('minimum gap>=-%.1e', cfg.feasibilityTolerance), ...
    sprintf('%.12g', minDominanceGap), ...
    "includes every deterministic, random-repeat and technical-benchmark prefix");

expectedGapRows = numel(cfg.years) * expectedGroupsPerYear * numel(cfg.erGrid);
add_check("efficiency_gap_row_count", height(gaps) == expectedGapRows, NaN, ...
    string(expectedGapRows), string(height(gaps)), "one row per group and ER budget");
add_check("random_gap_summary_rows", ...
    height(randomSummary) == numel(cfg.years) * numel(cfg.erGrid) && ...
    all(randomSummary.n_repeats == cfg.randomRepeats), NaN, ...
    sprintf('%d rows and %d repeats', ...
    numel(cfg.years) * numel(cfg.erGrid), cfg.randomRepeats), ...
    sprintf('%d rows', height(randomSummary)), "random distribution summary");

expectedKeyRows = numel(cfg.years) * numel(cfg.keyEta) * 10;
add_check("key_eta_summary_rows", height(keyEtaSummary) == expectedKeyRows, NaN, ...
    string(expectedKeyRows), string(height(keyEtaSummary)), ...
    "9 existing strategies plus 1 technical benchmark");

nonAuditFiles = string(manifest.files_created);
nonAuditFiles = nonAuditFiles(~contains(nonAuditFiles, "audit_report") & ...
    ~contains(nonAuditFiles, "audit_checks"));
missingOutputs = strings(0, 1);
for i = 1:numel(nonAuditFiles)
    if ~exist(fullfile(char(cfg.outputDir), char(nonAuditFiles(i))), 'file')
        missingOutputs(end + 1, 1) = nonAuditFiles(i); %#ok<AGROW>
    end
end
add_check("required_non_audit_outputs_exist", isempty(missingOutputs), NaN, ...
    "all", strjoin(missingOutputs, ';'), "date-prefixed independent outputs");

checkTable = cell2table(checks, 'VariableNames', ...
    {'check', 'status', 'year', 'expected', 'actual', 'detail'});
overallStatus = "PASS";
if any(checkTable.status ~= "PASS")
    overallStatus = "FAIL";
end

prefix = char(cfg.fileDatePrefix);
checksPath = fullfile(char(cfg.outputDir), ...
    [prefix 'transition_pareto_audit_checks.csv']);
reportPath = fullfile(char(cfg.outputDir), ...
    [prefix 'transition_pareto_audit_report.md']);
writetable(checkTable, checksPath);
write_report_local(reportPath, checkTable, overallStatus, cfg);

manifest.audit_status = char(overallStatus);
manifest.audit_report = reportPath;
manifest.audit_checks = checksPath;
write_manifest_local(manifest);
append_summary_status_local(manifest.summaryPath, overallStatus);

audit = struct();
audit.status = overallStatus;
audit.checks = checkTable;
audit.reportPath = string(reportPath);
audit.checksPath = string(checksPath);
audit.manifest = manifest;

    function add_check(name, condition, year, expected, actual, detail)
        status = "FAIL";
        if condition
            status = "PASS";
        end
        checks(end + 1, :) = {string(name), status, year, ...
            string(expected), string(actual), string(detail)};
    end
end

function [allOk, maxPhiDiff, maxERDiff, maxELDiff, maxCRDiff] = ...
        audit_prefix_groups_local(prefix, cfg)
groups = unique(prefix(:, {'year', 'strategy', 'repeat_id'}), ...
    'rows', 'stable');
allOk = true;
maxPhiDiff = 0;
maxERDiff = 0;
maxELDiff = 0;
maxCRDiff = 0;
for g = 1:height(groups)
    sub = prefix(prefix.year == groups.year(g) & ...
        prefix.strategy == groups.strategy(g) & ...
        prefix.repeat_id == groups.repeat_id(g), :);
    sub = sortrows(sub, 'K');
    allOk = allOk && height(sub) == cfg.nCities + 1 && ...
        isequal(sub.K, (0:cfg.nCities)');
    maxPhiDiff = max(maxPhiDiff, max(abs(sub.phi - sub.K / cfg.nCities)));
    maxERDiff = max(maxERDiff, max(abs(sub.economic_retention - ...
        (1 - sub.economic_loss))));
    expectedEL = cfg.mainTau * cumsum(sub.economic_share_added);
    expectedCR = cfg.mainTau * cumsum(sub.carbon_share_added);
    maxELDiff = max(maxELDiff, max(abs(sub.economic_loss - expectedEL)));
    maxCRDiff = max(maxCRDiff, max(abs(sub.carbon_reduction - expectedCR)));
end
end

function [allOk, maxELDiff, maxCRDiff, proxyCount] = ...
        audit_selections_local(frontier, selections, cfg)
allOk = true;
maxELDiff = 0;
maxCRDiff = 0;
proxyCount = sum(ismember(selections.city_code, cfg.excludedProxyCodes));
for i = 1:height(frontier)
    row = frontier(i, :);
    sub = selections(selections.year == row.year & ...
        abs(selections.eta - row.eta) <= cfg.objectiveTolerance, :);
    countOk = height(sub) == row.n_selected_cities;
    actualEL = sum(sub.economic_loss_contribution);
    actualCR = sum(sub.carbon_reduction_contribution);
    maxELDiff = max(maxELDiff, abs(actualEL - row.economic_loss));
    maxCRDiff = max(maxCRDiff, abs(actualCR - row.carbon_reduction));
    allOk = allOk && countOk && ...
        abs(actualEL - row.economic_loss) <= cfg.feasibilityTolerance && ...
        abs(actualCR - row.carbon_reduction) <= cfg.feasibilityTolerance;
end
end

function write_report_local(path, checks, status, cfg)
fid = fopen(path, 'w');
if fid < 0
    error('m37_transition_audit:OpenFailed', ...
        'Cannot write audit report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# 转型策略精确约束前沿与效率缺口审计报告\n\n');
fprintf(fid, '- 运行时间：%s\n', char(cfg.runTimestamp));
fprintf(fid, '- 冻结输入：`%s`\n', char(cfg.sourceTransitionDir));
fprintf(fid, '- 独立输出：`%s`\n', char(cfg.outputDir));
fprintf(fid, '- 求解器：Gurobi MATLAB API\n\n');
fprintf(fid, '| Check | Status | Year | Expected | Actual | Detail |\n');
fprintf(fid, '| --- | --- | ---: | --- | --- | --- |\n');
for i = 1:height(checks)
    yearText = '';
    if isfinite(checks.year(i))
        yearText = sprintf('%d', checks.year(i));
    end
    fprintf(fid, '| %s | %s | %s | %s | %s | %s |\n', ...
        clean_md_local(checks.check(i)), clean_md_local(checks.status(i)), ...
        yearText, clean_md_local(checks.expected(i)), ...
        clean_md_local(checks.actual(i)), clean_md_local(checks.detail(i)));
end
fprintf(fid, '\nTRANSITION_PARETO_AUDIT_STATUS = %s\n', status);
end

function text = clean_md_local(value)
text = char(replace(string(value), '|', '/'));
end

function write_manifest_local(manifest)
path = char(manifest.path);
json = jsonencode(manifest, 'PrettyPrint', true);
fid = fopen(path, 'w');
if fid < 0
    error('m37_transition_audit:ManifestOpenFailed', ...
        'Cannot update manifest: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fwrite(fid, json, 'char');
fwrite(fid, newline, 'char');
end

function append_summary_status_local(path, status)
fid = fopen(char(path), 'a');
if fid < 0
    error('m37_transition_audit:SummaryOpenFailed', ...
        'Cannot update run summary: %s', char(path));
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '\n\n=========\n\n## 最终审计\n\n');
fprintf(fid, '`TRANSITION_PARETO_AUDIT_STATUS = %s`\n', status);
end
