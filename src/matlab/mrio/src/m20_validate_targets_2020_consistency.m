function auditRow = m20_validate_targets_2020_consistency(targets, provTarget, mapping, varargin)
% M20_VALIDATE_TARGETS_2020_CONSISTENCY
% Check 2020 target-stage provincial consistency and write one machine-readable audit row.

p = inputParser;
p.addRequired('targets', @isstruct);
p.addRequired('provTarget', @isstruct);
p.addRequired('mapping', @isstruct);
p.addParameter('StageName', "targets", @(x) ischar(x) || isstring(x));
p.addParameter('Note', "", @(x) ischar(x) || isstring(x));
p.addParameter('OutputPath', "", @(x) ischar(x) || isstring(x));
p.addParameter('Append', false, @(x) islogical(x) || isnumeric(x));
p.addParameter('Tol', 1e-6, @(x) isnumeric(x) && isscalar(x) && x >= 0);
p.addParameter('Validate', true, @(x) islogical(x) || isnumeric(x));
p.parse(targets, provTarget, mapping, varargin{:});
opt = p.Results;

prov = cast_prov_2020(provTarget);
row = table( ...
    string(opt.StageName), ...
    "targets", ...
    inf_gap_2020(mapping.A * double(targets.X), prov.X), ...
    inf_gap_2020(mapping.A * double(targets.VA), prov.VA), ...
    inf_gap_2020(mapping.A * double(targets.IM), prov.IM), ...
    inf_gap_2020(mapping.A * double(targets.EX), prov.EX), ...
    inf_gap_2020(mapping.A * double(targets.error), prov.error), ...
    inf_gap_2020(mapping.A * double(targets.Y_city) * mapping.B', prov.Y), ...
    max([ ...
        inf_gap_2020(double(targets.prov_Z_row_target), sum(prov.Z, 2)), ...
        inf_gap_2020(double(targets.prov_Z_col_target), sum(prov.Z, 1)')]), ...
    max(abs(double(targets.X) - (double(targets.Z_row_target) + sum(double(targets.Y_row_by_fd), 2) + double(targets.EX) + double(targets.error)))), ...
    max(abs(double(targets.X) - (double(targets.Z_col_target) + double(targets.VA) + double(targets.IM)))), ...
    sum(double(targets.X)), ...
    sum(double(targets.VA)), ...
    sum(double(targets.IM)), ...
    sum(double(targets.EX)), ...
    sum(double(targets.error)), ...
    sum(double(targets.Y_city), 'all'), ...
    string(opt.Note), ...
    'VariableNames', {'stage','payload_kind','prov_X_inf','prov_VA_inf','prov_IM_inf','prov_EX_inf','prov_error_inf', ...
    'prov_Y_inf','prov_Z_inf','row_identity_max','col_identity_max','total_X','total_VA','total_IM','total_EX','total_error','total_Y','note'});
auditRow = row;

write_audit_row_2020(row, string(opt.OutputPath), logical(opt.Append));

if logical(opt.Validate)
    assert(row.prov_X_inf <= opt.Tol, 'm20_validate_targets_2020_consistency:ProvXFailed', ...
        '2020 targets failed prov_X_inf tolerance.');
    assert(row.prov_VA_inf <= opt.Tol, 'm20_validate_targets_2020_consistency:ProvVAFailed', ...
        '2020 targets failed prov_VA_inf tolerance.');
    assert(row.prov_IM_inf <= opt.Tol, 'm20_validate_targets_2020_consistency:ProvIMFailed', ...
        '2020 targets failed prov_IM_inf tolerance.');
    assert(row.prov_EX_inf <= opt.Tol, 'm20_validate_targets_2020_consistency:ProvEXFailed', ...
        '2020 targets failed prov_EX_inf tolerance.');
    assert(row.prov_Y_inf <= opt.Tol, 'm20_validate_targets_2020_consistency:ProvYFailed', ...
        '2020 targets failed prov_Y_inf tolerance.');
end
end

function prov = cast_prov_2020(prov)
fields = ["Z","Y","VA","IM","EX","X","error"];
for i = 1:numel(fields)
    if isfield(prov, fields(i))
        prov.(fields(i)) = double(prov.(fields(i)));
    else
        prov.(fields(i)) = zeros(size(prov.X));
    end
end
end

function write_audit_row_2020(row, outputPath, appendMode)
if strlength(strtrim(outputPath)) == 0
    return;
end
if appendMode && exist(outputPath, 'file')
    existing = readtable(outputPath, 'TextType', 'string');
    writetable([existing; row], outputPath); %#ok<AGROW>
else
    writetable(row, outputPath);
end
end

function value = inf_gap_2020(A, B)
value = max(abs(double(A(:)) - double(B(:))));
end
