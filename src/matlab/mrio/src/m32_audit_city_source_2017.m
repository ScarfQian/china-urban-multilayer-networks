function out = m32_audit_city_source_2017(cityInput, varargin)
% M32_AUDIT_CITY_SOURCE_2017
% Audit the 2017 city MRIO source table before any harmonization or backcast validation.

p = inputParser;
p.addRequired('cityInput');
p.addParameter('OutputDir', "", @(x) ischar(x) || isstring(x));
p.addParameter('FilePrefix', "city2017_source", @(x) ischar(x) || isstring(x));
p.parse(cityInput, varargin{:});
opt = p.Results;

city = resolve_city_input(cityInput);
outputDir = resolve_output_dir(opt.OutputDir);
ensure_dir(outputDir);

S = numel(city.sectors);
Nc = numel(city.cities);
NS = numel(city.X);
if NS ~= Nc * S
    error('m32_audit_city_source_2017:DimensionMismatch', ...
        'The city canonical struct is not consistent with city and sector counts.');
end

rowZ = sum(double(city.Z), 2);
rowY = sum(double(city.Y), 2);
rowRhs = rowZ + rowY + double(city.EX);
rowResidual = double(city.X) - rowRhs;

colZ = sum(double(city.Z), 1)';
colRhs = colZ + double(city.VA) + double(city.IM) + double(city.error);
colResidual = double(city.X) - colRhs;

[cityIndex, sectorIndex] = expand_city_sector_index(Nc, S);
rowTable = table( ...
    cityIndex, ...
    string(city.cities(cityIndex)), ...
    safe_city_cn(city, cityIndex), ...
    sectorIndex, ...
    string(city.sectors(sectorIndex)), ...
    double(city.X), ...
    rowZ, ...
    rowY, ...
    double(city.EX), ...
    rowRhs, ...
    rowResidual, ...
    abs(rowResidual), ...
    'VariableNames', {'city_id','city_name','city_name_cn','sector_id','sector_name', ...
    'X_raw','row_sum_Z','row_sum_Y','EX','row_identity_rhs','row_residual','abs_row_residual'});

colTable = table( ...
    cityIndex, ...
    string(city.cities(cityIndex)), ...
    safe_city_cn(city, cityIndex), ...
    sectorIndex, ...
    string(city.sectors(sectorIndex)), ...
    double(city.X), ...
    colZ, ...
    double(city.VA), ...
    double(city.IM), ...
    double(city.error), ...
    colRhs, ...
    colResidual, ...
    abs(colResidual), ...
    'VariableNames', {'city_id','city_name','city_name_cn','sector_id','sector_name', ...
    'X_raw','col_sum_Z','VA','IM','error','col_identity_rhs','col_residual','abs_col_residual'});

summaryMetric = [ ...
    "row_max_abs"; ...
    "row_mae"; ...
    "row_rmse"; ...
    "row_signed_sum"; ...
    "row_count_abs_gt_1"; ...
    "col_max_abs"; ...
    "col_mae"; ...
    "col_rmse"; ...
    "col_signed_sum"; ...
    "col_count_abs_gt_1"];

summaryValue = [ ...
    max(abs(rowResidual)); ...
    mean(abs(rowResidual)); ...
    sqrt(mean(rowResidual.^2)); ...
    sum(rowResidual); ...
    sum(abs(rowResidual) > 1); ...
    max(abs(colResidual)); ...
    mean(abs(colResidual)); ...
    sqrt(mean(colResidual.^2)); ...
    sum(colResidual); ...
    sum(abs(colResidual) > 1)];

summaryTable = table(summaryMetric, summaryValue, ...
    'VariableNames', {'metric','value'});

rowPath = fullfile(outputDir, sprintf('%s_row_residuals.csv', opt.FilePrefix));
colPath = fullfile(outputDir, sprintf('%s_col_residuals.csv', opt.FilePrefix));
summaryPath = fullfile(outputDir, sprintf('%s_audit_summary.csv', opt.FilePrefix));

writetable(rowTable, rowPath);
writetable(colTable, colPath);
writetable(summaryTable, summaryPath);

cityWithAudit = city;
cityWithAudit.X_row_reconciled = rowRhs;
cityRowReconciled = city;
cityRowReconciled.X = rowRhs;

out = struct();
out.city = cityWithAudit;
out.cityRowReconciled = cityRowReconciled;
out.rowResidualTable = rowTable;
out.colResidualTable = colTable;
out.summaryTable = summaryTable;
out.outputFiles = struct( ...
    'rowResiduals', string(rowPath), ...
    'colResiduals', string(colPath), ...
    'summary', string(summaryPath));
end

function city = resolve_city_input(cityInput)
if isstruct(cityInput) && isfield(cityInput, 'Z') && isfield(cityInput, 'Y')
    city = cityInput;
    return;
end
if ~(ischar(cityInput) || isstring(cityInput))
    error('m32_audit_city_source_2017:InvalidCityInput', ...
        'cityInput must be a canonical city struct or a MAT file path.');
end
city = m01_parse_city_mrio_mat(cityInput, 'Validate', false);
end

function outputDir = resolve_output_dir(outputDir)
outputDir = string(outputDir);
if strlength(strtrim(outputDir)) == 0
    outputDir = string(pwd);
end
end

function ensure_dir(dirPath)
if ~exist(dirPath, 'dir')
    mkdir(dirPath);
end
end

function [cityIndex, sectorIndex] = expand_city_sector_index(numCities, numSectors)
cityIndex = zeros(numCities * numSectors, 1);
sectorIndex = zeros(numCities * numSectors, 1);
cursor = 1;
for c = 1:numCities
    rows = cursor:(cursor + numSectors - 1);
    cityIndex(rows) = c;
    sectorIndex(rows) = (1:numSectors)';
    cursor = cursor + numSectors;
end
end

function cityCn = safe_city_cn(city, cityIndex)
if isfield(city, 'cities_cn') && numel(city.cities_cn) >= max(cityIndex)
    cityCn = string(city.cities_cn(cityIndex));
else
    cityCn = repmat("", numel(cityIndex), 1);
end
end
